function sawRadiusMul(ang) {
  const slot = TWO_PI / SAW_TEETH;
  let u = ang % slot;
  if (u < 0) u += slot;
  const tri = 1 - Math.abs((u / slot) * 2 - 1);
  return 0.78 + 0.22 * Math.pow(tri, 1.15);
}

/* Шестерёнка: зубчатый венец. Середина зуба — площадка на полном радиусе, между
   зубьями впадина глубиной GEAR_TOOTH_H, переходы скошены (GEAR_FLANK).
   Считается полярно, как у пилы и тыквы, поэтому одна и та же функция годится
   и для силуэта (pathGear), и для кромки под ножом (surfaceRadius). */
function gearRadiusMul(ang) {
  const slot = TWO_PI / GEAR_TEETH;
  let u = ang % slot;
  if (u < 0) u += slot;
  /* d: 0 — середина зуба, 1 — середина впадины */
  const d = Math.abs((u / slot) * 2 - 1);
  let q = (GEAR_TOOTH_W - d) / GEAR_FLANK;
  q = q < 0 ? 0 : q > 1 ? 1 : q;
  return 1 - GEAR_TOOTH_H + GEAR_TOOTH_H * q * q * (3 - 2 * q);
}

